import { test, expect } from '@playwright/test'

test('real garden: consent, seed, diary, task, reload and report', async ({page}) => {
  const errors: string[] = []; page.on('pageerror', error=>errors.push(error.message))
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('/')
  await expect(page.getByRole('button',{name:'进入我的花园'})).toBeDisabled()
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'进入我的花园'}).click()
  await page.getByRole('button',{name:'去花园播种'}).click()
  await page.getByRole('button',{name:/含羞草 焦虑/}).click()
  await page.getByLabel('发生了什么，让你有这样的感受？').fill('合成测试：明天汇报，担心准备不够。')
  await page.route('**/api/garden/entries',route=>route.abort(),{times:1})
  await page.getByRole('button',{name:'种下含羞草'}).click()
  await expect(page.getByRole('alert')).toContainText('暂时无法连接花园')
  await expect(page.getByLabel('发生了什么，让你有这样的感受？')).toHaveValue('合成测试：明天汇报，担心准备不够。')
  await page.getByRole('button',{name:'种下含羞草'}).click()
  const diary=page.getByRole('dialog',{name:'含羞草的成长日记'})
  await expect(diary).toBeVisible()
  await diary.getByLabel('脑中闪过的想法').fill('担心自己会讲不好')
  await diary.getByRole('button',{name:'保存日记',exact:true}).click()
  await expect(diary.getByText('这段日记已保存。')).toBeVisible()
  await diary.getByRole('button',{name:'照顾它的小行动'}).click()
  await diary.getByRole('button',{name:'加入任务簿'}).first().click()
  await expect(diary.getByRole('button',{name:'已加入'})).toBeDisabled()
  await diary.getByRole('button',{name:'关闭窗口'}).click()
  await page.getByRole('navigation').getByRole('button',{name:'任务簿',exact:true}).click()
  await page.getByRole('button',{name:'完成行动'}).click()
  await page.getByRole('dialog').getByRole('button',{name:'确认完成',exact:true}).click()
  await expect(page.getByText('已完成 · 谢谢你照顾自己')).toBeVisible()
  await page.reload()
  await expect(page.locator('.scene-plant')).toHaveCount(1)
  await page.screenshot({path:'test-results/garden-desktop.png',fullPage:true})
  await page.getByRole('navigation').getByRole('button',{name:'成长报告'}).click()
  await expect(page.getByText('这七天，你种下了 1 株情绪植物。',{exact:false})).toBeVisible()
  await page.getByRole('navigation').getByRole('button',{name:'树屋倾诉'}).click()
  await page.getByRole('button',{name:'考前有点慌'}).click()
  await expect(page.locator('.tree-message')).toHaveCount(2)
  await page.getByRole('navigation').getByRole('button',{name:'我的花园'}).click()
  await page.getByRole('navigation').getByRole('button',{name:'树屋倾诉'}).click()
  await expect(page.locator('.tree-message')).toHaveCount(0)
  const token=await page.evaluate(()=>localStorage.getItem('zhiyu.garden.token'))
  const deletion=await page.request.delete((process.env.E2E_API_BASE_URL ?? 'http://127.0.0.1:8080')+'/api/garden',{headers:{Authorization:`Bearer ${token}`}})
  expect(deletion.ok()).toBeTruthy()
  expect(errors).toEqual([])
})

test('mobile: no overflow and privacy deletion',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/')
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'进入我的花园'}).click()
  await expect(page.locator('.garden-scene')).toBeVisible()
  await page.screenshot({path:'test-results/garden-mobile.png',fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  await page.getByRole('button',{name:'隐私与我的数据'}).last().click()
  const dialog=page.getByRole('dialog')
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button',{name:'删除全部花园数据'}).click()
  await expect(page.getByRole('button',{name:'进入我的花园'})).toBeVisible()
})
